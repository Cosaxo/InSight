#!/usr/bin/env node
// build-ask-places.mjs — the city list the web buy door picks from.
//
//   node scripts/build-ask-places.mjs          # write web/ask-places.txt
//   node scripts/build-ask-places.mjs --check  # fail if it is stale
//
// WHY THIS FILE EXISTS AT ALL, which is the part worth reading before
// changing anything here. A paid ask scoped to a city carries
// `dims.city`, and the server matches that value against the anchor an
// ANSWER snapshotted when it was written (D8). That anchor is a catalogue
// key — `"Oslo, NO"`, name then a comma then the ISO 3166-1 alpha-2 code,
// which is `placeKey()` in src/v2/data/places.ts. So a buy door with a
// free-text city box would take someone's €320 and reach NOBODY: "Oslo",
// "oslo" and "Oslo, Norway" are all reasonable things to type and none of
// them is the key. The picker is not a convenience, it is the difference
// between a campaign and a refund.
//
// WHY NOT SERVE public/cities.txt ITSELF. That file is the app's, it is
// under Vite's public/ (which lands in dist/, not in the hosting root
// this page is served from), and 60% of its bytes are population and
// coordinates — data the device needs to answer "which city am I nearest"
// without a server, and data a buy page has no use for. 278 KB raw / 136
// KB gzipped against ~40 KB for the names alone, on a page whose whole
// design is one inline script and no framework.
//
// WHY NO COUNTRY NAMES. `Intl.DisplayNames` has all 245 in the reader's
// own language, which is what places.ts already does rather than shipping
// them — see its comment. The country picker's values are the alpha-2
// codes in this file's block headers, so this one resource feeds both.
//
// FORMAT, deliberately the source's own block shape minus the columns:
// a bare alpha-2 code opens a country block, every following line is one
// city name. `# ` opens a comment. Parsing it is four lines, which is the
// point on a page that may not load a library.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "public", "cities.txt");
const OUT = join(root, "web", "ask-places.txt");
const CHECK = process.argv.includes("--check");

const die = (m) => { console.error(`build-ask-places: ${m}`); process.exit(1); };

/** Country code -> city names, in the source's order (which is by
 *  population within a country, and that is the order the picker wants). */
export function trim(src) {
  const out = [];
  let cities = 0;
  let country = null;
  for (const raw of String(src).split("\n")) {
    const line = raw.trimEnd();
    if (!line || line.startsWith("#")) continue;
    if (!line.includes("\t")) {
      // A bare code opens a block. Held to shape rather than trusted: a
      // malformed source that slipped a stray word through here would
      // emit a "country" nothing can match, and the failure would show up
      // as a campaign reaching nobody rather than as an error.
      if (!/^[A-Z]{2}$/.test(line)) die(`not a country code: ${JSON.stringify(line)}`);
      country = line;
      out.push(line);
      continue;
    }
    if (!country) die("a city line appeared before any country block");
    const name = line.split("\t")[0].trim();
    if (!name) die(`a city line with no name in ${country}`);
    out.push(name);
    cities += 1;
  }
  if (!cities) die("no cities parsed — has the source format moved?");
  return { text: out.join("\n") + "\n", cities };
}

const src = readFileSync(SRC, "utf8");
const { text, cities } = trim(src);
const header =
  "# InSight buy-door city list — GENERATED by scripts/build-ask-places.mjs.\n"
  + "# Trimmed from public/cities.txt (GeoNames, CC BY 4.0): names only.\n"
  + `# ${cities} cities. A bare ISO 3166-1 alpha-2 code opens a country block;\n`
  + "# every following line is one city name. The value a booking carries is\n"
  + '# `"<name>, <CODE>"` — placeKey() in src/v2/data/places.ts, which is what\n'
  + "# an answer's stored anchor holds. Anything else reaches nobody.\n";
const body = header + text;

if (CHECK) {
  let have = "";
  try { have = readFileSync(OUT, "utf8"); } catch { die(`${OUT} is missing — run npm run build:ask-places`); }
  if (have !== body) die("web/ask-places.txt is stale — run npm run build:ask-places");
  console.log(`build-ask-places OK — ${cities} cities, in step with public/cities.txt.`);
} else {
  writeFileSync(OUT, body);
  console.log(`build-ask-places: wrote web/ask-places.txt — ${cities} cities.`);
}
