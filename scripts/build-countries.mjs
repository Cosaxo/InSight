// Generates public/countries.txt — the countries catalogue behind the
// feed's `pick` cards (docs/QUESTION-FARM.md § creating new catalogues;
// the domain machinery is docs/CATALOG-QUESTIONS.md / D14–D17).
//
// Source rules apply verbatim: `world-countries` is a devDependency used
// once, here (the `pokemon`/`unicode-emoji-json` pattern) — the
// mledoze/countries dataset, ODbL-licensed, all 250 ISO 3166-1 entries.
// Never hand-written entries; a wrong key silently resolves someone's
// stored answer to the wrong country forever.
//
// WHY ISO NUMERIC KEYS: the stored answer is an integer key, and ISO
// 3166-1 numeric codes are the standard's own stable identity for a
// country — they survive alpha-code changes and renames. ONE entry has
// no ISO numeric code: Kosovo (cca2 XK, itself a provisional code). It
// gets key 900, minted by this catalogue in ISO's user-assigned block
// and held stable by the append-only drift discipline — dropping the
// only entry the standard is undecided about would be an editorial
// statement this catalogue has no business making. Any OTHER entry
// arriving without a code fails the build loudly: minting is a recorded
// exception, never a fallback.
//
// Names are the dataset's `name.common` ("Norway", "South Korea"),
// alphabetical — there is no popularity column in ISO, and a neutral
// order beats a fabricated one. Search folds accents (catalogs.ts), so
// "sao tome" finds São Tomé and Príncipe.
import { createRequire } from "node:module";
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { regenerateCatalogKeys } from "./catalog-keys-lib.mjs";

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "public", "countries.txt");

let data;
try {
  data = require("world-countries");
} catch {
  console.error(
    "build-countries: `world-countries` is not installed.\n" +
      "It is a devDependency used only by this script:\n" +
      "  npm i --no-save world-countries@5.1.0",
  );
  process.exit(1);
}

// The one recorded mint (see header). Key 900 sits in ISO 3166-1's
// user-assigned numeric block, outside every assigned code.
const MINTED = { XK: 900 };

const rows = [];
const seenKeys = new Set();
const seenNames = new Set();
for (const c of data) {
  const name = c?.name?.common;
  if (!name) {
    console.error(`build-countries: entry without a common name: ${JSON.stringify(c?.cca2)}`);
    process.exit(1);
  }
  let key;
  if (/^\d{3}$/.test(c.ccn3 || "")) {
    key = Number(c.ccn3);
  } else if (MINTED[c.cca2] !== undefined) {
    key = MINTED[c.cca2];
  } else {
    console.error(`build-countries: ${name} (${c.cca2}) has no ISO numeric code and no recorded mint`);
    process.exit(1);
  }
  // Format corruption is a hard failure, never a filter.
  if (/[\t\n\r]/.test(name) || name.startsWith("#")) {
    console.error(`build-countries: name would corrupt the format: ${JSON.stringify(name)}`);
    process.exit(1);
  }
  if (key < 1 || seenKeys.has(key)) {
    console.error(`build-countries: bad or duplicate key ${key} (${name})`);
    process.exit(1);
  }
  const nk = name.toLowerCase();
  if (seenNames.has(nk)) {
    console.error(`build-countries: duplicate name ${JSON.stringify(name)} — search could not resolve it`);
    process.exit(1);
  }
  seenKeys.add(key);
  seenNames.add(nk);
  rows.push({ key, name });
}
if (rows.length < 240) {
  console.error(`build-countries: only ${rows.length} rows — refusing to write a stub catalogue`);
  process.exit(1);
}
rows.sort((a, b) => a.name.localeCompare(b.name, "en"));

const lines = [
  "# InSight countries catalogue — GENERATED by scripts/build-countries.mjs, do not edit.",
  "# Source: the mledoze/countries dataset via the `world-countries` npm",
  "# package (ODbL). Keys are ISO 3166-1 numeric codes — the standard's own",
  "# stable identity — except Kosovo (XK, no ISO numeric code): key 900,",
  "# minted in ISO's user-assigned block and held stable by the append-only",
  "# drift discipline. All 250 ISO entries, sovereign or not — the standard",
  "# decides what is listed, not this file.",
  `# ${rows.length} entries, alphabetical. Format: \`key<TAB>name\`.`,
];
for (const r of rows) lines.push(`${r.key}\t${r.name}`);
const text = lines.join("\n") + "\n";
writeFileSync(OUT, text);
console.log(
  `build-countries: wrote ${rows.length} countries — ` +
    `${(text.length / 1024).toFixed(1)} KB raw, ${(gzipSync(text).length / 1024).toFixed(1)} KB gzipped`,
);

// ── regenerate the trigger's key sets from ALL committed catalogues ─────
// One derivation for every builder: scripts/catalog-keys-lib.mjs.
regenerateCatalogKeys(root, "build-countries");
