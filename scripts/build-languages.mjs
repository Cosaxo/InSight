// Generates public/languages.txt — the language catalogue behind the
// feed's `pick` cards (docs/QUESTION-FARM.md § creating new catalogues;
// the domain machinery is docs/CATALOG-QUESTIONS.md / D14–D17).
//
// Source rules apply verbatim: `iso-639-1` is a devDependency used once,
// here (the `pokemon`/`dog-breeds` pattern) — the ISO 639-1 macro
// language set, MIT, 183 codes each carrying an English and a native
// name. Never hand-written entries; a wrong key silently resolves
// someone's stored answer to the wrong language forever.
//
// WHY MINTED KEYS, AND WHAT HOLDS THEM: ISO 639-1 codes are ALPHABETIC
// (`en`, `fr`) and every shipped catalogue keys on numbers, so keys are
// catalogue-minted under the manual's append-only discipline — the
// `dog-breeds` precedent, not the external-id one, and a deliberate
// choice stated in the domain PR rather than slipped in. The COMMITTED
// FILE is the registry of record, not the package: on regeneration this
// builder reads public/languages.txt first, preserves every existing
// key→name pair verbatim (a language the source later dropped or renamed
// STAYS — deleting it would orphan stored answers), and only appends
// genuinely new names with the next free keys. The initial mint is 1..N
// in ISO-code order; nothing after it may renumber.
//
// DISPLAY NAMES carry the native name in parens when it differs from the
// English one — "French (français)", but plain "Afrikaans" — the films
// catalogue's suffix precedent, so the picker resolves a search typed in
// either script. The suffix is display texture, not identity: the
// append-only match on regeneration compares the full stored name.
import { createRequire } from "node:module";
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { regenerateCatalogKeys } from "./catalog-keys-lib.mjs";

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "public", "languages.txt");

let iso;
try {
  iso = require("iso-639-1");
} catch {
  console.error(
    "build-languages: `iso-639-1` is not installed.\n" +
      "It is a devDependency used only by this script:\n" +
      "  npm i --no-save iso-639-1@3.1.6",
  );
  process.exit(1);
}

// Names from the source, in ISO-code order (the initial mint's order),
// format-checked. Native name joins in parens only when it differs.
const sourceNames = [];
const seen = new Set();
for (const code of iso.getAllCodes().sort()) {
  const en = (iso.getName(code) || "").trim();
  const native = (iso.getNativeName(code) || "").trim();
  if (!en) {
    console.error(`build-languages: code ${code} has no English name`);
    process.exit(1);
  }
  const name = native && native.toLowerCase() !== en.toLowerCase() ? `${en} (${native})` : en;
  if (/[\t\n\r]/.test(name) || name.startsWith("#")) {
    console.error(`build-languages: name would corrupt the format: ${JSON.stringify(name)}`);
    process.exit(1);
  }
  const nk = name.toLowerCase();
  if (seen.has(nk)) {
    console.error(`build-languages: duplicate name ${JSON.stringify(name)} — search could not resolve it`);
    process.exit(1);
  }
  seen.add(nk);
  sourceNames.push(name);
}
if (sourceNames.length < 150) {
  console.error(`build-languages: only ${sourceNames.length} rows — refusing to write a stub catalogue`);
  process.exit(1);
}

// ── the append-only mint (build-dogs.mjs's discipline, verbatim) ───────
const existing = []; // [key, name] in file order
const existingByName = new Map();
let maxKey = 0;
if (existsSync(OUT)) {
  for (const line of readFileSync(OUT, "utf8").split("\n")) {
    if (!line || line.startsWith("#")) continue;
    const tab = line.indexOf("\t");
    if (tab < 1) continue;
    const key = Number(line.slice(0, tab));
    const name = line.slice(tab + 1);
    existing.push({ key, name });
    existingByName.set(name.toLowerCase(), key);
    if (key > maxKey) maxKey = key;
  }
}

const rows = [...existing];
const fresh = sourceNames.filter((n) => !existingByName.has(n.toLowerCase()));
for (const name of fresh) rows.push({ key: ++maxKey, name });
// First generation: `existing` is empty, so every name is fresh and the
// mint comes out 1..N in ISO-code order.

const lines = [
  "# InSight languages catalogue — GENERATED by scripts/build-languages.mjs, do not edit.",
  "# Source: ISO 639-1 via the `iso-639-1` npm package (MIT). Keys are",
  "# CATALOGUE-MINTED and append-only (ISO codes are alphabetic, and every",
  "# shipped catalogue keys on numbers): this committed file is the registry",
  "# of record — regeneration preserves every existing key→name pair",
  "# verbatim and only appends new names with the next free keys. An entry",
  "# never renumbers and never leaves; stored answers depend on it. Names",
  "# carry the native name in parens when it differs from the English one.",
  `# ${rows.length} entries, initial mint in ISO-code order. Format: \`key<TAB>name\`.`,
];
for (const r of rows) lines.push(`${r.key}\t${r.name}`);
const text = lines.join("\n") + "\n";
writeFileSync(OUT, text);
const gz = gzipSync(Buffer.from(text)).length;
console.log(
  `build-languages: wrote ${rows.length} languages to public/languages.txt ` +
    `(${text.length} bytes, ~${(gz / 1024).toFixed(1)} KiB gzipped)`,
);

regenerateCatalogKeys(root, "build-languages");
