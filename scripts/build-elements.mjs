// Generates public/elements.txt — the periodic-table catalogue behind the
// `pick` question type's picker (docs/CATALOG-QUESTIONS.md), fourth domain.
//
// WHY A GENERATED, COMMITTED ARTIFACT — the build-pokedex.mjs argument
// verbatim: the `periodic-table` package is a devDependency used once,
// here, and never reaches a bundle. The output is committed so a clean
// checkout builds without it; `npm run check:elements` validates the
// committed file (format, not regeneration — same split as
// check-pokedex.mjs).
//
// WHY `z<TAB>name` AND NOT BARE NAMES IN ORDER: the stored answer is the
// atomic number — an answer is a catalogue key, never a string. Atomic
// numbers are the most stable keys any domain here will ever get: they are
// physics, contiguous from 1 by construction, and IUPAC does not renumber.
//
// Display names carry the symbol — "Gold (Au)" — so the picker's search
// matches either; both are unique across the set (probed, not assumed).
//
// Data: the `periodic-table` npm package (ISC). Element names and symbols
// are IUPAC nomenclature — facts, not trademarks; no naming posture to
// clear, which makes this the portfolio's least encumbered domain.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "public", "elements.txt");

let pt;
try {
  pt = require("periodic-table");
} catch {
  console.error(
    "build-elements: `periodic-table` is not installed.\n" +
      "It is a devDependency used only by this script:\n" +
      "  npm i --no-save periodic-table@0.0.8",
  );
  process.exit(1);
}

const all = pt.all().slice().sort((a, b) => a.atomicNumber - b.atomicNumber);

// Contiguity is the whole point of a {max} range domain: a gap would mean
// a key the backend accepts that the catalogue cannot resolve. The other
// checks mirror build-pokedex.mjs — a tab or newline corrupts the format
// itself, a duplicate makes search ambiguous; both are hard failures.
const problems = [];
all.forEach((e, i) => {
  if (e.atomicNumber !== i + 1) problems.push(`atomicNumber ${e.atomicNumber} at position ${i + 1}`);
  const display = `${e.name} (${e.symbol})`;
  if (!e.name || !e.symbol || /[\t\n\r#]/.test(display) || display !== display.trim()) {
    problems.push(`malformed entry at z=${e.atomicNumber}: ${JSON.stringify(display)}`);
  }
});
const displays = all.map((e) => `${e.name} (${e.symbol})`);
if (new Set(displays).size !== displays.length) problems.push("duplicate display names");
if (problems.length) {
  console.error(`build-elements: ${problems.length} problem(s) in the dataset:`);
  for (const p of problems.slice(0, 5)) console.error(`  - ${p}`);
  process.exit(1);
}

const lines = [
  "# InSight elements catalogue — GENERATED by scripts/build-elements.mjs, do not edit.",
  "# Source: the `periodic-table` npm package (ISC); IUPAC names + symbols.",
  `# ${all.length} elements. Format: \`z<TAB>Name (Symbol)\`; z (atomic number) is`,
  "# contiguous from 1 and is the stored answer key",
  "# (docs/CATALOG-QUESTIONS.md: a key, never a string).",
  "#",
  "# Element names are IUPAC nomenclature — facts, not trademarks.",
];
all.forEach((e) => lines.push(`${e.atomicNumber}\t${e.name} (${e.symbol})`));
const text = lines.join("\n") + "\n";

writeFileSync(OUT, text);
console.log(
  `build-elements: wrote ${all.length} elements — ` +
    `${(text.length / 1024).toFixed(1)} KB raw, ${(gzipSync(text).length / 1024).toFixed(1)} KB gzipped`,
);
